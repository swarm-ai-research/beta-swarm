"""Tests for posterior inference over proxy parameters.

The load-bearing test is :class:`TestGradient` — a hand-derived gradient that is
subtly wrong still produces a smooth, plausible-looking posterior centred on the
wrong place, and nothing downstream would catch it. Everything else checks that
the sampler is honest about its own failures.
"""

from __future__ import annotations

import numpy as np
import pytest
from scipy import stats

from beta_swarm.agents import Archetype
from beta_swarm.inference import hmc
from beta_swarm.inference.proxy_posterior import (
    N_PARAMS,
    ProxyPosterior,
    ProxyTheta,
    design_from_observables,
    natural_draws,
)
from beta_swarm.proxy import BetaProxyComputer


