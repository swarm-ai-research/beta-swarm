def _synthetic_design(n=400, seed=0, theta=None):
    """Draw observables from the archetype emission model, outcomes from `theta`.

    Outcomes are generated by the *model being fitted*, so parameter recovery is
    a real test of the estimator rather than of model misspecification.
    """
    rng = np.random.default_rng(seed)
    from beta_swarm.agents import SimAgent

    agents = [SimAgent.make(a.value, a) for a in (Archetype.HONEST, Archetype.MEDIOCRE)]
    obs_list, latent = [], []
    for _ in range(n):
        agent = agents[rng.integers(len(agents))]
        v = agent.sample_outcome(rng)
        obs_list.append(agent.emit_observables(v, rng))
        latent.append(v)

    if theta is None:
        return obs_list, latent

    proxy = theta.to_proxy()
    outcomes = [float(proxy.compute_belief(o).sample(rng)) for o in obs_list]
    return obs_list, outcomes


@pytest.fixture(scope="module")
def design():
    obs, outcomes = _synthetic_design(n=300, seed=1)
    return design_from_observables(obs, outcomes)


