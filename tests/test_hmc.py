class TestGradient:
    """The analytic gradient against central finite differences.

    If this fails, every posterior in this package is wrong.
    """

    @pytest.mark.parametrize("seed", [0, 1, 2, 3, 4])
    def test_matches_finite_differences(self, design, seed):
        rng = np.random.default_rng(seed)
        post = ProxyPosterior(design)
        u = post.prior_mean + rng.normal(scale=0.4, size=N_PARAMS)

        value, grad = post.log_prob_and_grad(u)
        assert np.isfinite(value)

        eps = 1e-6
        numeric = np.empty(N_PARAMS)
        for j in range(N_PARAMS):
            up, dn = u.copy(), u.copy()
            up[j] += eps
            dn[j] -= eps
            numeric[j] = (post.log_prob(up) - post.log_prob(dn)) / (2 * eps)

        np.testing.assert_allclose(grad, numeric, rtol=2e-5, atol=2e-5)

    def test_value_agrees_with_direct_beta_logpdf(self, design):
        """The likelihood must be the Beta density the proxy actually produces."""
        u = np.array([0.2, -0.3, 0.1, np.log(2.0), np.log(2.0), np.log(1.5)])
        post = ProxyPosterior(design)
        proxy = ProxyTheta.from_vector(u).to_proxy()

        total = 0.0
        for i in range(len(design)):
            mean = 1.0 / (1.0 + np.exp(-proxy.sigmoid_k * (design.features[i] @ proxy._w)))
            conc = proxy.base_concentration + proxy.evidence_scale * design.evidence[i]
            total += stats.beta.logpdf(design.outcomes[i], mean * conc, (1 - mean) * conc)
        prior = -0.5 * np.sum(((u - post.prior_mean) / post.prior_sd) ** 2)

        assert post.log_prob(u) == pytest.approx(total + prior, rel=1e-10)

    def test_gradient_is_zero_at_an_interior_optimum(self, design):
        """Gradient ascent must reach a point the analytic gradient calls flat."""
        post = ProxyPosterior(design)
        u = post.init_point()
        for _ in range(4000):
            _, g = post.log_prob_and_grad(u)
            u = u + 1e-4 * g
        _, g = post.log_prob_and_grad(u)
        assert np.max(np.abs(g)) < 1e-2 * len(design)


