class TestParameterRecovery:
    """End to end: simulate from known parameters, confirm the posterior covers them."""

    def test_posterior_covers_the_truth(self):
        truth = ProxyTheta(
            w=np.array([0.5, 0.2, 0.2, 0.1]),
            sigmoid_k=2.5,
            base_concentration=3.0,
            evidence_scale=1.2,
        )
        obs, outcomes = _synthetic_design(n=1500, seed=4, theta=truth)
        post = ProxyPosterior(design_from_observables(obs, outcomes))

        rng = np.random.default_rng(0)
        res = hmc.sample(
            post, init=post.dispersed_inits(4, rng),
            n_draws=600, n_warmup=600, n_chains=4, seed=17,
        )
        assert res.diagnostics.divergences == 0, res.diagnostics.summary()
        assert np.all(res.diagnostics.rhat < 1.02), res.diagnostics.summary()

        nat = natural_draws(res.draws)
        lo, hi = np.quantile(nat.reshape(-1, nat.shape[-1]), [0.005, 0.995], axis=0)
        true_vec = truth.to_vector()
        covered = (lo <= true_vec) & (true_vec <= hi)
        # 99% marginal intervals on 7 parameters: allow one miss to noise.
        assert covered.sum() >= 6, (
            f"only {covered.sum()}/7 covered\n"
            f"truth={np.round(true_vec, 3)}\nlo={np.round(lo, 3)}\nhi={np.round(hi, 3)}"
        )

    def test_tail_mass_interval_is_nondegenerate(self):
        """The whole point: the governance lever gets an error bar."""
        from beta_swarm.inference.proxy_posterior import posterior_tail_mass

        obs, outcomes = _synthetic_design(n=400, seed=6)
        post = ProxyPosterior(design_from_observables(obs, outcomes))
        rng = np.random.default_rng(1)
        res = hmc.sample(
            post, init=post.dispersed_inits(2, rng),
            n_draws=300, n_warmup=400, n_chains=2, seed=21,
        )
        tm = posterior_tail_mass(res.draws, obs[:25], tau=0.4, max_draws=100)
        assert tm.shape == (100, 25)
        assert np.all((tm >= 0.0) & (tm <= 1.0)), "p must stay in [0, 1]"

        # Uncertainty is *not* uniform across interactions, and asserting on the
        # median hides that. Most interactions are saturated — tail mass pinned
        # near 0 or 1, where no plausible parameter value changes the call, so
        # the spread is ~1e-10. The uncertainty concentrates on the borderline
        # cases, which are exactly the ones where a threshold call is close.
        # That concentration is the argument for carrying a posterior at all,
        # so it is what this test pins down.
        spread = tm.max(axis=0) - tm.min(axis=0)
        assert spread.max() > 0.05, (
            f"no interaction has materially uncertain tail mass "
            f"(max spread {spread.max():.2g}); the posterior is adding nothing"
        )
        assert np.mean(spread > 0.01) >= 0.1, (
            f"only {np.mean(spread > 0.01):.0%} of interactions carry meaningful "
            f"tail-mass uncertainty"
        )

    def test_tail_mass_uncertainty_concentrates_on_borderline_cases(self):
        """Spread must track distance from the threshold, not be noise."""
        from beta_swarm.inference.proxy_posterior import posterior_tail_mass

        obs, outcomes = _synthetic_design(n=400, seed=6)
        post = ProxyPosterior(design_from_observables(obs, outcomes))
        rng = np.random.default_rng(1)
        res = hmc.sample(
            post, init=post.dispersed_inits(2, rng),
            n_draws=300, n_warmup=400, n_chains=2, seed=21,
        )
        subset = obs[:60]
        tm = posterior_tail_mass(res.draws, subset, tau=0.4, max_draws=100)
        spread = tm.max(axis=0) - tm.min(axis=0)
        # Distance of the posterior-median tail mass from the 0.5 decision line.
        distance = np.abs(np.median(tm, axis=0) - 0.5)
        # Negative correlation: the closer to the line, the wider the interval.
        r = np.corrcoef(distance, spread)[0, 1]
        assert r < -0.3, f"uncertainty does not track borderline-ness (r={r:.2f})"
