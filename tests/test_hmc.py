class TestSampler:
    def test_recovers_a_correlated_gaussian(self):
        """A target whose answer is known in closed form."""
        cov = np.array([[1.0, 0.85], [0.85, 1.4]])
        prec = np.linalg.inv(cov)

        def logp_and_grad(q):
            g = -prec @ q
            return float(-0.5 * q @ prec @ q), g

        res = hmc.sample(
            logp_and_grad, init=np.zeros(2),
            n_draws=1500, n_warmup=1000, n_chains=4, seed=11,
        )
        assert res.diagnostics.divergences == 0
        assert np.all(res.diagnostics.rhat < 1.01)
        np.testing.assert_allclose(res.mean(), np.zeros(2), atol=0.08)
        np.testing.assert_allclose(np.cov(res.flat.T), cov, atol=0.12)

    def test_step_size_adapts_toward_target(self):
        def logp_and_grad(q):
            return float(-0.5 * q @ q), -q

        res = hmc.sample(
            logp_and_grad, init=np.zeros(3),
            n_draws=600, n_warmup=600, n_chains=2, seed=5, target_accept=0.8,
        )
        for rate in res.diagnostics.accept_rate:
            assert 0.6 < rate < 0.95

    def test_rejects_non_finite_start(self):
        def logp_and_grad(q):
            return -np.inf, np.zeros_like(q)

        with pytest.raises(ValueError, match="initial log density"):
            hmc.sample(logp_and_grad, init=np.zeros(2), n_draws=10, n_warmup=10)

    def test_chain_count_mismatch_rejected(self):
        def logp_and_grad(q):
            return float(-0.5 * q @ q), -q

        with pytest.raises(ValueError, match="n_chains"):
            hmc.sample(
                logp_and_grad, init=np.zeros((3, 2)),
                n_draws=10, n_warmup=10, n_chains=4,
            )


class TestDiagnosticsCanFail:
    """A diagnostic that cannot fire is decoration. These make each one fire."""

    def test_funnel_produces_divergences(self):
        """Neal's funnel: curvature no fixed step size can track.

        Betancourt's central example. The sampler must *report* the failure
        rather than return clean-looking draws from the funnel's mouth.
        """
        def logp_and_grad(q):
            v, x = q[0], q[1:]
            if abs(v) > 30:
                return -np.inf, np.zeros_like(q)
            logp = -0.5 * (v / 3.0) ** 2 - 0.5 * np.sum(x**2) * np.exp(-v) - 4.5 * v
            gv = -v / 9.0 + 0.5 * np.sum(x**2) * np.exp(-v) - 4.5
            gx = -x * np.exp(-v)
            return float(logp), np.concatenate([[gv], gx])

        res = hmc.sample(
            logp_and_grad, init=np.zeros(10),
            n_draws=600, n_warmup=600, n_chains=2, seed=3, target_accept=0.8,
        )
        d = res.diagnostics
        assert d.divergences > 0, "funnel must produce divergences"
        assert any("divergent" in w for w in d.warnings())

    def test_rhat_detects_disagreeing_chains(self):
        """Two well-separated modes, chains started in each, must not look mixed."""
        def logp_and_grad(q):
            # Mixture of two sharp Gaussians at -8 and +8; the barrier between
            # them is far too high for any chain to cross.
            a, b = q - 8.0, q + 8.0
            la = -0.5 * np.sum(a**2)
            lb = -0.5 * np.sum(b**2)
            m = max(la, lb)
            tot = m + np.log(np.exp(la - m) + np.exp(lb - m))
            wa = np.exp(la - m) / (np.exp(la - m) + np.exp(lb - m))
            return float(tot), -(wa * a + (1 - wa) * b)

        inits = np.array([[-8.0], [8.0], [-8.0], [8.0]])
        res = hmc.sample(
            logp_and_grad, init=inits,
            n_draws=500, n_warmup=500, n_chains=4, seed=2,
        )
        assert res.diagnostics.rhat[0] > 1.01
        assert any("R-hat" in w for w in res.diagnostics.warnings())

    def test_clean_run_reports_no_warnings(self):
        def logp_and_grad(q):
            return float(-0.5 * q @ q), -q

        res = hmc.sample(
            logp_and_grad, init=np.zeros(2),
            n_draws=1500, n_warmup=1000, n_chains=4, seed=9,
        )
        assert res.diagnostics.warnings() == []
        assert "OK" in res.diagnostics.summary()


class TestDiagnosticFunctions:
    def test_rhat_near_one_for_iid_draws(self):
        rng = np.random.default_rng(0)
        draws = rng.normal(size=(4, 2000, 3))
        assert np.all(hmc.split_rhat(draws) < 1.01)

    def test_ess_near_n_for_iid_draws(self):
        rng = np.random.default_rng(0)
        draws = rng.normal(size=(4, 2000, 2))
        ess = hmc.effective_sample_size(draws)
        assert np.all(ess > 0.7 * 8000)

    def test_ess_drops_for_correlated_draws(self):
        rng = np.random.default_rng(0)
        x = np.zeros((4, 2000, 1))
        for c in range(4):
            for t in range(1, 2000):
                x[c, t, 0] = 0.95 * x[c, t - 1, 0] + rng.normal()
        assert hmc.effective_sample_size(x)[0] < 0.15 * 8000

    def test_constant_parameter_reports_nan_not_one(self):
        """A frozen coordinate is un-converged, not perfectly converged."""
        draws = np.ones((4, 100, 1))
        assert np.isnan(hmc.split_rhat(draws)[0])

    def test_ebfmi_is_low_for_a_slowly_drifting_energy(self):
        slow = np.cumsum(np.random.default_rng(0).normal(size=2000)) * 0.1
        assert hmc.ebfmi(slow) < 0.3
        fast = np.random.default_rng(0).normal(size=2000)
        assert hmc.ebfmi(fast) > 1.0


